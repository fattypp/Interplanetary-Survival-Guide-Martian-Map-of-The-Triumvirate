#!/usr/bin/env python3
"""
Bridge between the Python crater model and the web page.

  python integration/web_bridge.py detect   run the model, write web/data/craters-data.js
  python integration/web_bridge.py bundle   inline css, js, images and data into dist/jezero-delta-atlas.html
  python integration/web_bridge.py missiondata   write web/data/mission-data.js from docs/mission-guide.md
  python integration/web_bridge.py layers   run model/science_layers.py, write web/data/science-layers-data.js (needs opencv and scikit-learn)
  python integration/web_bridge.py all      detect, missiondata, then bundle (does not run `layers`: its output is committed)

  bundle takes --out PATH to write somewhere other than dist/ (dry runs).

Why a data .js file and not a .json: the page then opens straight from disk (file://)
with no local server. Why a bundle: a single self-contained HTML file is what the
Claude Artifact publisher (and any static host) needs.
"""
import argparse, base64, csv, json, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODEL = ROOT / "model" / "crater_detector.py"
WEB = ROOT / "web"
IMAGE = WEB / "images" / "jezero-ctx-mosaic.jpg"
DATA_JS = WEB / "data" / "craters-data.js"
OUT_DIR = ROOT / "model" / "output"
DIST = ROOT / "dist" / "jezero-delta-atlas.html"
KEEP = ("id", "lat", "lon", "diameter_m", "class", "confidence", "page")   # fields the page uses

# The map area. Fetch the image for it with integration/fetch_ctx.py (same corners), then run detect.
NW = (18.57188, 77.22318)        # lat, lon of the north-west corner
SE = (18.44176, 77.41956)        # lat, lon of the south-east corner
ZMIN = 3.5                       # matched-filter strength; the model's default 4.5 finds just 1 crater in this crater-poor area
SEEDS = ["28,350,26", "1037,115,17", "693,581,10", "913,543,45"]   # x,y,radius of clean craters in the image (sun direction)


def detect(threshold):
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    raw = OUT_DIR / "craters.json"
    cmd = [sys.executable, str(MODEL), str(IMAGE), "--out", str(raw),
           "--preview", str(OUT_DIR / "preview.png"), "--threshold", str(threshold), "--zmin", str(ZMIN),
           "--bbox", str(NW[1]), str(SE[0]), str(SE[1]), str(NW[0])]
    for sd in SEEDS:
        cmd += ["--seed", sd]
    print("running model:", " ".join(cmd))
    subprocess.run(cmd, check=True)
    data = json.loads(raw.read_text())
    slim = {"meta": {k: v for k, v in data["meta"].items() if k != "image"},   # drop the local file path
             "craters": [{k: c[k] for k in KEEP} for c in data["craters"]]}
    DATA_JS.write_text("/* Generated by integration/web_bridge.py. Do not edit by hand. */\n"
                       "window.JEZERO_CRATERS = " + json.dumps(slim, separators=(",", ":")) + ";\n")
    print(f"wrote {DATA_JS.relative_to(ROOT)} ({len(slim['craters'])} craters)")
    write_csv(data["craters"])


def write_csv(craters):
    cols = ["Crater ID", "Size class", "Diameter (m)", "Latitude (deg N)", "Longitude (deg E)", "Confidence (0-1)",
            "Image X (px)", "Image Y (px)", "Image radius (px)", "Page X", "Page Y", "Page radius"]
    with open(ROOT / "craters.csv", "w", newline="", encoding="utf-8-sig") as f:   # utf-8-sig so Excel shows the degree signs
        w = csv.writer(f)
        w.writerow(cols)
        for c in craters:
            w.writerow([c["id"], c["class"].capitalize(), c["diameter_m"], f"{c['lat']:.5f}", f"{c['lon']:.5f}",
                        f"{c['confidence']:.2f}", *c["px"], *c["page"]])
    print(f"wrote craters.csv ({len(craters)} rows)")


def data_uri(path):
    mime = {".jpg": "image/jpeg", ".png": "image/png"}[path.suffix.lower()]
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode()


MISSION_GUIDE = ROOT.parent / "docs" / "mission-guide.md"
MISSION_JS = WEB / "data" / "mission-data.js"


# Atlas page geometry (the same formula as Atlas.xy in web/js/atlas-map.js: page 1990 x 1390 over the NW/SE corners above)
PAGE_W, PAGE_H = 1990, 1390
LON0, LAT1, DLON, DLAT = NW[1], NW[0], SE[1] - NW[1], NW[0] - SE[0]


def to_xy(lat, lon):
    return round((lon - LON0) / DLON * PAGE_W, 1), round((LAT1 - lat) / DLAT * PAGE_H, 1)


def md_table(text, section, cols):
    """Rows of the first table under '## <section>' as lists of cells; the header must match `cols` exactly."""
    rows, inside, header_seen = [], False, False
    for no, line in enumerate(text.splitlines(), 1):
        if re.match(r"##\s+" + re.escape(section) + r"\s*$", line):
            inside = True
            continue
        if inside and re.match(r"##\s", line):
            break
        if not inside or not line.lstrip().startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if not header_seen:
            header_seen = True
            if cells != cols:
                raise SystemExit(f"mission-guide.md line {no}: '{section}' table header must be {' | '.join(cols)}")
            continue
        if all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
            continue
        if len(cells) != len(cols):
            raise SystemExit(f"mission-guide.md line {no}: expected {len(cols)} columns, found {len(cells)}")
        rows.append((no, cells))
    if not header_seen:
        raise SystemExit(f"mission-guide.md: section '## {section}' with a table not found")
    return rows


def lat_lon(no, lat, lon):
    try:
        la, lo = float(lat), float(lon)
    except ValueError:
        raise SystemExit(f"mission-guide.md line {no}: lat and lon must be numbers")
    if not (SE[0] <= la <= NW[0] and NW[1] <= lo <= SE[1]):
        raise SystemExit(f"mission-guide.md line {no}: {la}, {lo} is outside the atlas map "
                         f"({SE[0]} to {NW[0]} N, {NW[1]} to {SE[1]} E)")
    return la, lo


def parse_mission_guide(text):
    """Parse docs/mission-guide.md into {"objectives", "base", "stops", "tasks"} (the JEZERO_MISSION contract in
    docs/MULTIPAGE.md). Any deviation (not 2 objectives, not exactly 5 stops, not exactly one task per stop and objective,
    bad ids, positions outside the map, estMin outside 20..60) stops the generator with a message instead of writing bad data."""
    objectives = []
    for no, (n, title, short) in md_table(text, "Mission Objectives", ["Id", "Title", "Short"]):
        if not n.isdigit() or int(n) != len(objectives) + 1 or not title or not short:
            raise SystemExit(f"mission-guide.md line {no}: objective ids must be 1, 2 in order, with title and short")
        objectives.append({"id": int(n), "title": title, "short": short})
    if [o["id"] for o in objectives] != [1, 2]:
        raise SystemExit("mission-guide.md: exactly 2 objectives (1 and 2) are required")

    base, stops, ids = None, [], set()
    for no, (sid, name, lat, lon, desc) in md_table(text, "Mission Stops", ["Id", "Name", "Lat", "Lon", "Description"]):
        la, lo = lat_lon(no, lat, lon)
        x, y = to_xy(la, lo)
        if not name or sid in ids:
            raise SystemExit(f"mission-guide.md line {no}: empty name or duplicate id {sid!r}")
        ids.add(sid)
        if sid == "base":
            if base:
                raise SystemExit(f"mission-guide.md line {no}: more than one base row")
            base = {"id": "base", "name": name, "lat": la, "lon": lo, "x": x, "y": y}
            continue
        n = len(stops) + 1
        if sid != f"stop-{n}":
            raise SystemExit(f"mission-guide.md line {no}: stop ids must be stop-1 .. stop-5 in order (found {sid!r})")
        stops.append({"id": sid, "n": n, "name": name, "lat": la, "lon": lo, "x": x, "y": y, "description": desc})
    if not base:
        raise SystemExit("mission-guide.md: the base row (id 'base') is missing")
    if len(stops) != 5:
        raise SystemExit(f"mission-guide.md: exactly 5 stops are required, found {len(stops)}")

    tasks, seen = [], set()
    for no, (tid, stop, obj, title, desc, est) in md_table(text, "Mission Tasks", ["Id", "Stop", "Objective", "Title", "Description", "Est. min"]):
        if stop not in ids or stop == "base":
            raise SystemExit(f"mission-guide.md line {no}: unknown stop {stop!r}")
        if obj not in ("1", "2"):
            raise SystemExit(f"mission-guide.md line {no}: objective must be 1 or 2")
        if tid != f"task-{stop.split('-')[1]}-{obj}" or tid in seen:
            raise SystemExit(f"mission-guide.md line {no}: task id must be task-<stop number>-<objective> and unique (found {tid!r})")
        if not title or not desc or not est.isdigit() or not 20 <= int(est) <= 60:
            raise SystemExit(f"mission-guide.md line {no}: title, description and an estimate of 20 to 60 minutes are required")
        seen.add(tid)
        tasks.append({"id": tid, "stopId": stop, "objective": int(obj), "title": title, "description": desc, "estMin": int(est)})
    want = {f"task-{n}-{o}" for n in range(1, 6) for o in (1, 2)}
    if seen != want or len(tasks) != 10:
        raise SystemExit(f"mission-guide.md: exactly 10 tasks are required (one per stop and objective); missing {sorted(want - seen)}")
    order = {s["id"]: i for i, s in enumerate(stops)}
    tasks.sort(key=lambda t: (order[t["stopId"]], t["objective"]))   # stop order, Objective 1 first
    return {"objectives": objectives, "base": base, "stops": stops, "tasks": tasks}


def layers():
    """Regenerate web/data/science-layers-data.js (simulated radiation / relief / texture-class layers)."""
    subprocess.run([sys.executable, str(ROOT / "model" / "science_layers.py")], check=True)


def missiondata():
    if not MISSION_GUIDE.exists():
        raise SystemExit(f"missiondata failed: {MISSION_GUIDE} not found")
    data = parse_mission_guide(MISSION_GUIDE.read_text(encoding="utf-8"))
    MISSION_JS.write_text("/* Generated by integration/web_bridge.py from docs/mission-guide.md. Do not edit by hand. */\n"
                          "window.JEZERO_MISSION = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"wrote {MISSION_JS.relative_to(ROOT)} ({len(data['objectives'])} objectives, base camp, {len(data['stops'])} stops, {len(data['tasks'])} tasks)")


def local_file(ref, kind):
    """Resolve a '../css/x.css' style reference from web/html/index.html; fail loudly if it is missing."""
    p = (WEB / "html" / ref).resolve()
    if not p.is_file():
        raise SystemExit(f"bundle failed: {kind} {ref!r} referenced in a web/html page does not exist ({p})")
    return p


PAGE_NAMES = {"index.html": "jezero-delta-atlas.html", "earth.html": "earth-control.html", "helmet.html": "astronaut-helmet.html",
              "tablet.html": "astronaut-tablet.html", "control.html": "simulation-control.html"}


def bundle(out=None):
    """Build a single-file dist page for every web/html/*.html. --out only redirects the main atlas page (for dry runs)."""
    for src in sorted((WEB / "html").glob("*.html")):
        dest = DIST.parent / PAGE_NAMES.get(src.name, src.name)
        bundle_page(src.name, Path(out) if out and src.name == "index.html" else dest)


def bundle_page(page, out):
    html = (WEB / "html" / page).read_text(encoding="utf-8")

    def css_sub(m):
        return "<style>\n" + local_file(m.group(1), "stylesheet").read_text(encoding="utf-8") + "\n</style>"

    def js_sub(m):
        body = local_file(m.group(1), "script").read_text(encoding="utf-8").replace("</script", "<\\/script")
        return "<script>\n" + body + "\n</script>"

    # local stylesheets (../...) only; the Google Fonts link (https://) is kept as is
    html = re.sub(r'<link\s+rel="stylesheet"\s+href="(\.\./[^"]+)"\s*/?>', css_sub, html)
    html = re.sub(r'<script\s+src="(\.\./[^"]+)"\s*>\s*</script>', js_sub, html)
    html = re.sub(r'src="\.\./images/([^"]+)"', lambda m: f'src="{data_uri(local_file("../images/" + m.group(1), "image"))}"', html)
    # images referenced from inlined CSS (url(../images/x)) or from inlined JS string literals ('../images/x')
    def img_sub(m):
        return m.group(1) + data_uri(local_file("../images/" + m.group(2), "image")) + m.group(3)
    html = re.sub(r"(url\(\s*['\"]?)\.\./images/([^)'\"\s]+)(['\"]?\s*\))", img_sub, html)
    html = re.sub(r"(['\"])\.\./images/([^'\"\s]+)(['\"])", img_sub, html)
    left = re.findall(r'(?:href|src)="\.\./[^"]*"', html) + re.findall(r"\.\./images/[\w.-]+", html)
    if left:
        raise SystemExit(f"bundle failed: unresolved local references left in the page: {left}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")
    try:
        shown = out.relative_to(ROOT)
    except ValueError:
        shown = out
    print(f"wrote {shown} ({len(html) // 1024} KB)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["detect", "missiondata", "layers", "bundle", "all"])
    ap.add_argument("--out", help="bundle: write here instead of dist/jezero-delta-atlas.html (for dry runs)")
    ap.add_argument("--threshold", type=float, default=0.5, help="model confidence cut-off (default 0.5)")
    a = ap.parse_args()
    if a.command in ("detect", "all"):
        detect(a.threshold)
    if a.command in ("missiondata", "all"):
        missiondata()
    if a.command == "layers":
        layers()
    if a.command in ("bundle", "all"):
        bundle(a.out)
